export function t(lang, key, vars) {
  const table = strings[lang] || strings.en;
  let text = table[key] ?? strings.en[key] ?? key;
  if (vars) {
    text = String(text).replace(/\{(\w+)\}/g, (_, name) =>
      vars[name] == null || vars[name] === "" ? "" : String(vars[name])
    );
  }
  return text;
}
